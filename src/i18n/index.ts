const dict: Record<Language, Partial<Record<keyof typeof hu, string>>> = { hu, en };

/** exported for the coverage test */
export const dictionaries = { hu, en };

export type StringKey = keyof typeof hu;

export function translate(
  lang: Language,
  key: StringKey,
  vars?: Record<string, string | number>
): string {
  let s = dict[lang]?.[key] ?? hu[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, String(v));
    }
  }
  return s;
}

/** React hook: a jelenlegi nyelvhez kötött fordító függvény. */
export function useT() {
  const lang = useSettingsStore((s) => s.settings.language);
  return (key: StringKey, vars?: Record<string, string | number>) =>
    translate(lang, key, vars);
}
